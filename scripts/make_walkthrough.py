F = {}
def font(size, style="sans"):
    key=(size,style)
    if key not in F:
        path={"sans":FONT_SANS,"bold":FONT_SANS_BOLD,"serif":FONT_SERIF,"serifbold":FONT_SERIF_BOLD}.get(style,FONT_SANS)
        F[key]=ImageFont.truetype(path,size)
    return F[key]

def rounded(draw, box, radius=12, fill=PANEL, outline=(68,52,35), width=1):
    draw.rounded_rectangle(box, radius, fill=fill, outline=outline, width=width)

def txt(draw, xy, value, size=16, color=INK, style="sans", anchor=None):
    draw.text(xy, value, font=font(size,style), fill=color, anchor=anchor)

def wrap_lines(text, max_chars):
    return textwrap.wrap(text, width=max_chars, break_long_words=False)

def paragraph(draw, xy, text, max_chars=62, size=14, color=MUTED, line_gap=7, style="sans"):
    x,y=xy
    for line in wrap_lines(text,max_chars):
        txt(draw,(x,y),line,size,color,style); y += size + line_gap
    return y

def chip(draw,x,y,label,fill=(45,34,23),outline=(100,77,49),color=GOLD_LIGHT,fs=10,pad=10):
    width=draw.textbbox((0,0),label,font=font(fs))[2]+pad*2
    rounded(draw,(x,y,x+width,y+26),7,fill,outline,1)
    txt(draw,(x+pad,y+6),label,fs,color)
    return x+width+7

