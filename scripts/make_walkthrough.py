RENDERERS=[scene_hero,scene_profiles,scene_detail,scene_date,scene_rankings,scene_tech]

def main():
    if not shutil.which('ffmpeg') or not shutil.which('espeak'):
        raise SystemExit('Requires ffmpeg and espeak on PATH.')
    segments=[]
    for i,(spec,renderer) in enumerate(zip(SCENES,RENDERERS),1):
        png=OUT/f'scene-{i:02d}.png'; wav=OUT/f'voice-{i:02d}.wav'; mp4=OUT/f'segment-{i:02d}.mp4'
        renderer().save(png)
        subprocess.run(['espeak','-v','en-us','-s','158','-p','42','-a','165','-w',str(wav),spec['voice']],check=True,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
        # Preserve a fraction of silence after narration so the scene is readable.
        audio_len=float(subprocess.check_output(['ffprobe','-v','error','-show_entries','format=duration','-of','default=nw=1:nk=1',str(wav)],text=True).strip())
        duration=audio_len+0.85
        subprocess.run(['ffmpeg','-y','-loglevel','error','-loop','1','-framerate','25','-i',str(png),'-i',str(wav),'-t',f'{duration:.3f}','-vf','format=yuv420p','-c:v','libx264','-preset','veryfast','-crf','24','-r','25','-c:a','aac','-b:a','128k','-shortest',str(mp4)],check=True)
        segments.append(mp4)
        print(f'Scene {i}: {audio_len:.1f}s narration')
    concat=OUT/'segments.txt'
    concat.write_text(''.join(f"file '{p.as_posix()}'\n" for p in segments),encoding='utf-8')
    final=ROOT/'kindred-prototype-walkthrough.mp4'
    subprocess.run(['ffmpeg','-y','-loglevel','error','-f','concat','-safe','0','-i',str(concat),'-c','copy','-movflags','+faststart',str(final)],check=True)
